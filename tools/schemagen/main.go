// Command schemagen generates Go types and Effect Schemas from the shared
// JSON Schema in schema/forkit.schema.json.
//
// It supports the subset of JSON Schema the data model uses: named $defs that
// are objects, string enums or branded primitives; properties that are
// primitives, $refs, arrays or string-keyed maps; and minimum/maximum on
// numbers.
//
// Optional properties and all arrays use omitempty on the Go side. Arrays
// decode a missing key as [] in TypeScript, so a nil Go slice and an empty one
// mean the same thing on the wire.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"slices"
	"sort"
	"strings"
)

type node struct {
	Type                 string          `json:"type"`
	Format               string          `json:"format"`
	Description          string          `json:"description"`
	Enum                 []string        `json:"enum"`
	Ref                  string          `json:"$ref"`
	Required             []string        `json:"required"`
	Items                *node           `json:"items"`
	AdditionalProperties json.RawMessage `json:"additionalProperties"`
	Minimum              *float64        `json:"minimum"`
	Maximum              *float64        `json:"maximum"`
	RawProperties        json.RawMessage `json:"properties"`

	properties []property
}

type property struct {
	name   string
	schema *node
}

type definition struct {
	name   string
	schema *node
}

func main() {
	schemaPath := flag.String("schema", "", "path to the JSON Schema")
	goOut := flag.String("go", "", "Go output file")
	tsOut := flag.String("ts", "", "TypeScript output file")
	flag.Parse()

	defs, err := load(*schemaPath)
	if err != nil {
		log.Fatal(err)
	}
	goSrc, err := format.Source(newGoGenerator(defs).generate())
	if err != nil {
		log.Fatalf("formatting Go output: %v", err)
	}
	if err := os.WriteFile(*goOut, goSrc, 0o644); err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*tsOut, generateTS(defs), 0o644); err != nil {
		log.Fatal(err)
	}
}

func load(path string) ([]definition, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var root struct {
		Defs json.RawMessage `json:"$defs"`
	}
	if err := json.Unmarshal(raw, &root); err != nil {
		return nil, err
	}
	names, err := orderedKeys(root.Defs)
	if err != nil {
		return nil, err
	}
	var byName map[string]*node
	if err := json.Unmarshal(root.Defs, &byName); err != nil {
		return nil, err
	}
	defs := make([]definition, 0, len(names))
	for _, name := range names {
		schema := byName[name]
		if err := resolveProperties(schema); err != nil {
			return nil, fmt.Errorf("%s: %w", name, err)
		}
		defs = append(defs, definition{name: name, schema: schema})
	}
	return defs, nil
}

func resolveProperties(n *node) error {
	if n.Items != nil {
		if err := resolveProperties(n.Items); err != nil {
			return err
		}
	}
	if valueSchema := mapValueSchema(n); valueSchema != nil {
		if err := resolveProperties(valueSchema); err != nil {
			return err
		}
	}
	if n.RawProperties == nil {
		return nil
	}
	names, err := orderedKeys(n.RawProperties)
	if err != nil {
		return err
	}
	var byName map[string]*node
	if err := json.Unmarshal(n.RawProperties, &byName); err != nil {
		return err
	}
	for _, name := range names {
		if err := resolveProperties(byName[name]); err != nil {
			return fmt.Errorf("%s: %w", name, err)
		}
		n.properties = append(n.properties, property{name: name, schema: byName[name]})
	}
	return nil
}

// orderedKeys returns the keys of a JSON object in document order, which
// encoding/json's map decoding loses.
func orderedKeys(raw json.RawMessage) ([]string, error) {
	dec := json.NewDecoder(bytes.NewReader(raw))
	if _, err := dec.Token(); err != nil {
		return nil, err
	}
	var keys []string
	for dec.More() {
		tok, err := dec.Token()
		if err != nil {
			return nil, err
		}
		keys = append(keys, tok.(string))
		var skip json.RawMessage
		if err := dec.Decode(&skip); err != nil {
			return nil, err
		}
	}
	return keys, nil
}

// mapValueSchema returns the value schema of a string-keyed map, or nil when
// the node is not a map.
func mapValueSchema(n *node) *node {
	if len(n.AdditionalProperties) == 0 || n.AdditionalProperties[0] != '{' || n.RawProperties != nil {
		return nil
	}
	var value node
	if err := json.Unmarshal(n.AdditionalProperties, &value); err != nil {
		log.Fatalf("additionalProperties: %v", err)
	}
	return &value
}

func refName(ref string) string {
	return strings.TrimPrefix(ref, "#/$defs/")
}

func (n *node) isOptional(prop string) bool {
	return !slices.Contains(n.Required, prop)
}

const header = "Code generated by tools/schemagen from schema/forkit.schema.json. DO NOT EDIT."

type goGenerator struct {
	defs       []definition
	defsByName map[string]*node
}

func newGoGenerator(defs []definition) *goGenerator {
	byName := map[string]*node{}
	for _, def := range defs {
		byName[def.name] = def.schema
	}
	return &goGenerator{defs: defs, defsByName: byName}
}

func (g *goGenerator) generate() []byte {
	var b strings.Builder
	fmt.Fprintf(&b, "// %s\n\npackage model\n\n", header)
	for _, def := range g.defs {
		writeGoDoc(&b, "", def.schema.Description)
		s := def.schema
		switch {
		case len(s.Enum) > 0:
			typeName := goName(def.name)
			fmt.Fprintf(&b, "type %s string\n\nconst (\n", typeName)
			for _, value := range s.Enum {
				fmt.Fprintf(&b, "\t%s%s %s = %q\n", typeName, goName(value), typeName, value)
			}
			b.WriteString(")\n\n")
		case s.Type == "object":
			fmt.Fprintf(&b, "type %s %s\n\n", goName(def.name), g.goType(s))
		default:
			fmt.Fprintf(&b, "type %s %s\n\n", goName(def.name), goPrimitive(s))
		}
	}
	return []byte(b.String())
}

func (g *goGenerator) goType(n *node) string {
	switch {
	case n.Ref != "":
		return goName(refName(n.Ref))
	case n.Type == "array":
		return "[]" + g.goType(n.Items)
	case mapValueSchema(n) != nil:
		return "map[string]" + g.goType(mapValueSchema(n))
	case n.Type == "object":
		return g.goStruct(n)
	case n.Type == "":
		return "any"
	default:
		return goPrimitive(n)
	}
}

func goPrimitive(n *node) string {
	switch n.Type {
	case "string":
		return "string"
	case "boolean":
		return "bool"
	case "integer":
		if n.Format == "int64" {
			return "int64"
		}
		return "int"
	case "number":
		return "float64"
	}
	log.Fatalf("unsupported type %q", n.Type)
	return ""
}

func (g *goGenerator) goStruct(n *node) string {
	var b strings.Builder
	b.WriteString("struct {\n")
	for _, prop := range n.properties {
		writeGoDoc(&b, "\t", prop.schema.Description)
		fieldType := g.goType(prop.schema)
		tag := prop.name
		if n.isOptional(prop.name) || prop.schema.Type == "array" {
			tag += ",omitempty"
		}
		if n.isOptional(prop.name) && g.needsPointerWhenOptional(prop.schema) {
			fieldType = "*" + fieldType
		}
		fmt.Fprintf(&b, "\t%s %s `json:%q`\n", goName(prop.name), fieldType, tag)
	}
	b.WriteString("}")
	return b.String()
}

// needsPointerWhenOptional reports whether a field's zero value is meaningful,
// so absence has to be represented by nil instead. An empty string never is.
func (g *goGenerator) needsPointerWhenOptional(n *node) bool {
	if n.Ref != "" {
		return g.needsPointerWhenOptional(g.defsByName[refName(n.Ref)])
	}
	return n.Type == "integer" || n.Type == "number" || n.Type == "boolean" || (n.Type == "object" && mapValueSchema(n) == nil)
}

func writeGoDoc(b *strings.Builder, indent, description string) {
	if description != "" {
		fmt.Fprintf(b, "%s// %s\n", indent, description)
	}
}

var goInitialisms = map[string]string{"Id": "ID", "Oid": "OID", "Url": "URL", "Otlp": "OTLP", "Ff": "FF"}

// goName converts a camelCase or kebab-case identifier into an exported Go
// name, upper-casing common initialisms.
func goName(name string) string {
	var words []string
	start := 0
	for i := 1; i <= len(name); i++ {
		if i == len(name) || name[i] == '-' || (name[i] >= 'A' && name[i] <= 'Z') {
			words = append(words, strings.TrimPrefix(name[start:i], "-"))
			start = i
		}
	}
	var b strings.Builder
	for _, word := range words {
		if word == "" {
			continue
		}
		word = strings.ToUpper(word[:1]) + word[1:]
		if initialism, ok := goInitialisms[word]; ok {
			word = initialism
		}
		b.WriteString(word)
	}
	return b.String()
}

func generateTS(defs []definition) []byte {
	var b strings.Builder
	fmt.Fprintf(&b, "// %s\n\nimport { Effect, Schema } from \"effect\"\n\n", header)
	b.WriteString("const emptyArray = Schema.withDecodingDefaultKey(Effect.succeed([]))\n")
	for _, def := range dependencyOrder(defs) {
		s := def.schema
		if s.Description != "" {
			fmt.Fprintf(&b, "\n/** %s */", s.Description)
		}
		var expr string
		switch {
		case len(s.Enum) > 0:
			expr = tsLiterals(s.Enum)
		case s.Type == "object":
			expr = tsType(s, "")
		default:
			expr = fmt.Sprintf("%s.pipe(Schema.brand(%q))", tsType(s, ""), def.name)
		}
		fmt.Fprintf(&b, "\nexport const %s = %s\nexport type %s = typeof %s.Type\n", def.name, expr, def.name, def.name)
	}
	return []byte(b.String())
}

func tsType(n *node, indent string) string {
	switch {
	case n.Ref != "":
		return refName(n.Ref)
	case len(n.Enum) > 0:
		return tsLiterals(n.Enum)
	case n.Type == "array":
		return fmt.Sprintf("Schema.Array(%s)", tsType(n.Items, indent))
	case mapValueSchema(n) != nil:
		return fmt.Sprintf("Schema.Record(Schema.String, %s)", tsType(mapValueSchema(n), indent))
	case n.Type == "object":
		return tsStruct(n, indent)
	case n.Type == "":
		return "Schema.Unknown"
	case n.Type == "string":
		return "Schema.String"
	case n.Type == "boolean":
		return "Schema.Boolean"
	case n.Type == "integer":
		return withBounds("Schema.Int", n)
	case n.Type == "number":
		return withBounds("Schema.Finite", n)
	}
	log.Fatalf("unsupported type %q", n.Type)
	return ""
}

func withBounds(base string, n *node) string {
	if n.Minimum == nil || n.Maximum == nil {
		return base
	}
	return fmt.Sprintf("%s.pipe(Schema.check(Schema.isBetween({ minimum: %v, maximum: %v })))", base, *n.Minimum, *n.Maximum)
}

func tsStruct(n *node, indent string) string {
	var b strings.Builder
	b.WriteString("Schema.Struct({\n")
	inner := indent + "  "
	for _, prop := range n.properties {
		expr := tsType(prop.schema, inner)
		switch {
		case prop.schema.Type == "array":
			expr += ".pipe(emptyArray)"
		case n.isOptional(prop.name):
			expr = fmt.Sprintf("Schema.optionalKey(%s)", expr)
		}
		fmt.Fprintf(&b, "%s%s: %s,\n", inner, prop.name, expr)
	}
	b.WriteString(indent + "})")
	return b.String()
}

func tsLiterals(values []string) string {
	quoted := make([]string, len(values))
	for i, v := range values {
		quoted[i] = fmt.Sprintf("%q", v)
	}
	return fmt.Sprintf("Schema.Literals([%s])", strings.Join(quoted, ", "))
}

// dependencyOrder sorts definitions so each one follows everything it
// references, because TypeScript consts must be declared before use.
func dependencyOrder(defs []definition) []definition {
	byName := map[string]definition{}
	for _, def := range defs {
		byName[def.name] = def
	}
	var ordered []definition
	visited := map[string]bool{}
	var visit func(name string)
	visit = func(name string) {
		if visited[name] {
			return
		}
		visited[name] = true
		deps := references(byName[name].schema)
		sort.Strings(deps)
		for _, dep := range deps {
			visit(dep)
		}
		ordered = append(ordered, byName[name])
	}
	for _, def := range defs {
		visit(def.name)
	}
	return ordered
}

func references(n *node) []string {
	var refs []string
	if n.Ref != "" {
		refs = append(refs, refName(n.Ref))
	}
	if n.Items != nil {
		refs = append(refs, references(n.Items)...)
	}
	if valueSchema := mapValueSchema(n); valueSchema != nil {
		refs = append(refs, references(valueSchema)...)
	}
	for _, prop := range n.properties {
		refs = append(refs, references(prop.schema)...)
	}
	return refs
}
